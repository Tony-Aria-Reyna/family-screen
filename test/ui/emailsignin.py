# Signing in with an email address and password (for family members without a Google account, e.g. Outlook on an iPhone)
import asyncio
from playwright.async_api import async_playwright
U='http://localhost:5500/index.html'
ADMIN='tonyandreynanz@gmail.com'; M='masako@outlook.com'
async def main():
    async with async_playwright() as p:
        b=await p.chromium.launch(); ctx=await b.new_context(timezone_id='Pacific/Auckland',locale='en-NZ')
        errs=[]
        def mk(pg,tag): pg.on('pageerror',lambda e:errs.append(tag+': '+str(e)))
        F=await ctx.new_page(); mk(F,'tony'); await F.set_viewport_size({'width':1280,'height':800})
        await F.goto(U); await F.wait_for_timeout(500)
        await F.evaluate(f"localStorage.setItem('fs.askedMe',JSON.stringify(['{ADMIN}'])); SYNC.testSignIn('{ADMIN}')"); await F.wait_for_timeout(700)
        await F.click('#gNew'); await F.wait_for_timeout(800)
        await F.click('#setBtn'); await F.wait_for_timeout(300)
        await F.fill('#mIn', M); await F.click('#mAdd'); await F.wait_for_timeout(600)
        print('1 settings explains email sign-in:', await F.locator('text=Sign in with email').count()>0, '| members:', await F.evaluate("SYNC.getMembers().join(',')"))
        await F.click('#ok')
        P=await ctx.new_page(); mk(P,'masako'); await P.set_viewport_size({'width':390,'height':844})
        await P.goto(U); await P.wait_for_timeout(600)
        print('2 sign-in screen has the email button:', await P.locator('#gMail').count()==1)
        await P.click('#gMail'); await P.wait_for_timeout(200)
        await P.fill('#gEm', M); await P.fill('#gPw','wrongpass1'); await P.click('#gGo'); await P.wait_for_timeout(300)
        print('3 no account yet:', await P.locator('.gerr').inner_text())
        await P.click('#gNewPw'); await P.wait_for_timeout(200)
        print('4 address carried over:', await P.input_value('#gEm'))
        await P.fill('#gPw','short'); await P.click('#gGo'); await P.wait_for_timeout(200)
        print('5 short password:', await P.locator('.gerr').inner_text())
        await P.fill('#gPw','Machan-2026'); await P.click('#gShow'); print('6 show password:', await P.get_attribute('#gPw','type'))
        await P.click('#gGo'); await P.wait_for_timeout(800)
        print('7 after creating:', await P.locator('#gate h1').inner_text(), '| emails:', await P.evaluate("localStorage.getItem('mockmail')"))
        await P.screenshot(path='/tmp/email_verify.png')
        await P.click('#gVer'); await P.wait_for_timeout(300)
        print('8 before tapping the link:', await P.locator('.gerr').inner_text())
        await P.evaluate(f"(()=>{{const a=JSON.parse(localStorage.getItem('mockaccts')); a['{M}'].verified=true; localStorage.setItem('mockaccts',JSON.stringify(a));}})()")
        await P.click('#gVer'); await P.wait_for_timeout(1500)
        print('9 after the link: home open', await P.evaluate("document.getElementById('gate').hidden"), '| signed in as', await P.evaluate("SYNC.me()"), '| family:', await P.evaluate("S.people.map(p=>p.name).join(',')"))
        await P.evaluate("SYNC.signOut()"); await P.wait_for_timeout(500)
        await P.click('#gMail'); await P.fill('#gEm', M.upper()); await P.fill('#gPw','Machan-2026'); await P.click('#gGo'); await P.wait_for_timeout(1500)
        print('10 signed back in with the password: home open', await P.evaluate("document.getElementById('gate').hidden"))
        await P.evaluate("SYNC.signOut()"); await P.wait_for_timeout(500)
        await P.click('#gMail'); print('11a address remembered:', await P.input_value('#gEm')); await P.fill('#gEm',''); await P.click('#gForgot'); await P.wait_for_timeout(200)
        print('11 forgot, no address:', await P.locator('.gerr').inner_text())
        await P.fill('#gEm', M); await P.click('#gForgot'); await P.wait_for_timeout(300)
        print('12 forgot:', await P.locator('.gnote').inner_text())
        await P.click('#gNewPw'); await P.fill('#gPw','another-pass'); await P.click('#gGo'); await P.wait_for_timeout(400)
        print('13 create again:', await P.locator('.gerr').inner_text())
        await P.click('#gHave'); await P.wait_for_timeout(200); await P.screenshot(path='/tmp/email_signin.png')
        print('14 Tony still signed in on the fridge:', await F.evaluate("SYNC.me()"))
        print('errors:', errs)
        await b.close()
asyncio.run(main())
